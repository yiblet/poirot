//! Generate Unicode, cached-string continuation and relative-reference XLS fixtures.
//! Run `cargo run -p poirot-xls --example repro`; files are written to `/tmp/poirot-xls`.
use poirot_model::{CellValue, Workbook};
fn main() -> Result<(), Box<dyn std::error::Error>> {
    let directory = std::path::Path::new("/tmp/poirot-xls");
    std::fs::create_dir_all(directory)?;
    for kind in [
        "unicode-formula",
        "unicode-name",
        "long-cached-string-continuation",
        "relative-area",
    ] {
        let mut w = Workbook::new();
        w.add_sheet("Data")?;
        match kind {
            "unicode-formula" => w
                .sheet_mut(0)
                .ok_or("Data worksheet is missing")?
                .set_formula_with_cached_value(
                    "A1".parse()?,
                    "\"😀\"",
                    CellValue::Text("😀".into()),
                )?,
            "unicode-name" => {
                w.define_name("名称", "1", None)?;
                w.sheet_mut(0)
                    .ok_or("Data worksheet is missing")?
                    .set_formula_with_cached_value("A1".parse()?, "名称", CellValue::Number(1.))?
            }
            "long-cached-string-continuation" => {
                // SAFETY: The literal has seven UTF-8 bytes; 6000 copies require only 42000 bytes.
                let text = format!("{}END", "a😀é".repeat(6000));
                w.sheet_mut(0)
                    .ok_or("Data worksheet is missing")?
                    .set_value("A1".parse()?, text.clone())?;
                w.sheet_mut(0)
                    .ok_or("Data worksheet is missing")?
                    .set_formula_with_cached_value("B1".parse()?, "A1", CellValue::Text(text))?
            }
            _ => {
                w.sheet_mut(0)
                    .ok_or("Data worksheet is missing")?
                    .set_value("A1".parse()?, 2.)?;
                w.sheet_mut(0)
                    .ok_or("Data worksheet is missing")?
                    .set_formula_with_cached_value(
                        "B1".parse()?,
                        "SUM(A1:A1)",
                        CellValue::Number(2.),
                    )?
            }
        }
        poirot_xls::write_xls(&w, directory.join(format!("{kind}.xls")))?;
    }
    std::fs::write(
        directory.join("PROVENANCE.md"),
        "Generated by crates/poirot-xls/examples/repro.rs from typed poirot models. BIFF layout grounded in pinned POI HSSF/record and ss/formula/ptg serializers. No Excel, LibreOffice, or Docker observation claimed. Four probes isolate calamine0.36.1 Unicode StringPtg byte skips, Unicode defined-name character byte length, cached STRING CONTINUE import, and relative AreaPtg flag masking. Writer unit tests independently inspect encoded records plus SST and cached STRING continuations.\n",
    )?;
    Ok(())
}
