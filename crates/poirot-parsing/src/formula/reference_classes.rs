/// Function return channel used to preserve reference and array semantics during translation.
#[derive(Clone, Copy, PartialEq, Eq)]
pub(super) enum ReturnClass {
    /// Call can preserve reference geometry for its consumer.
    Reference,
    /// Call returns an ordinary value rather than a reference.
    Value,
    /// Call may return an array requiring array-aware consumption.
    Array,
}
/// Classify builtin return channels for formula translation and reference handling.
pub(super) fn return_class(name: &str) -> Option<ReturnClass> {
    lookup(name, false)
}
/// ASCII case-insensitive lookup without materializing an uppercase spelling.
pub(super) fn return_class_insensitive(name: &str) -> Option<ReturnClass> {
    lookup(name, true)
}
