//! Independent elementary inverse controls, without distribution round trips.
use super::*;
fn meter(_: u64) -> std::result::Result<(), ()> {
    Ok(())
}
#[track_caller]
fn near(value: Result<()>, expected: f64, tolerance: f64) {
    let actual = value.unwrap();
    assert!(
        (actual - expected).abs()
            <= if expected == 0.0 {
                1e-15
            } else {
                expected.abs() * tolerance
            },
        "{actual:e} != {expected:e}"
    );
}
#[test]
fn elementary_beta_gamma_and_f_quantiles() {
    near(beta(0.25, 1., 1., 2., 6., meter), 3., 1e-13);
    near(beta(0.25, 2., 1., 0., 1., meter), 0.5, 1e-13);
    near(beta(0.75, 1., 2., 0., 1., meter), 0.5, 1e-13);
    near(beta(0.5, 2., 2., -1e308, 1e308, meter), 0., 1e-13);
    for p in [1e-300, 1e-20, 0.25, 0.5, 0.9, 1. - f64::EPSILON] {
        near(
            gamma(p, 1., 2., Tail::Lower, meter),
            -2. * (-p).ln_1p(),
            2e-13,
        );
        near(chi_square(p, 2., Tail::Upper, meter), -2. * p.ln(), 2e-13);
        near(fisher_f(p, 2., 2., Tail::Lower, meter), p / (1. - p), 2e-13);
        near(fisher_f(p, 2., 2., Tail::Upper, meter), (1. - p) / p, 2e-13);
    }
    let scaled_beta = beta(1e-300, 0.5, 1., 0., 1e308, meter).unwrap();
    assert!((scaled_beta / 1e-292 - 1.).abs() < 3e-13);
    // Dimensionless x would underflow; scale restores a finite worksheet value.
    near(
        gamma(1e-300, 0.5, 1e300, Tail::Lower, meter),
        std::f64::consts::PI * 0.25 * 1e-300,
        3e-13,
    );
}
#[test]
fn cauchy_student_and_normal_controls() {
    for (p, x) in [(0.25, -1.), (0.5, 0.), (0.75, 1.)] {
        near(student_t(p, 1., false, meter), x, 2e-12);
    }
    near(student_t(0.5, 1., true, meter), 1., 2e-12);
    near(student_t(0.75, 2., false, meter), (2f64 / 3.).sqrt(), 2e-12);
    near(
        confidence(0.5, 2., 2., ConfidenceKind::Student, meter),
        2f64.sqrt(),
        2e-12,
    );
    near(lognormal::<()>(0.5, 3f64.ln(), 7.), 3., 2e-13);
    // Independently solve the high precision integral of exp(-t*t/2)/sqrt(2*pi).
    near(
        confidence(0.05, 1., 1., ConfidenceKind::Normal, meter),
        1.959_963_984_540_054_2,
        2e-14,
    );
    near(lognormal::<()>(1e-20, 0., 1.), 9.493291347224353e-5, 2e-13);
    near(
        confidence(1e-300, 1., 1., ConfidenceKind::Normal, meter),
        37.06578788077213,
        2e-14,
    );
}
#[test]
fn binomial_smallest_integer_and_truncation() {
    // Coefficients of (1+x)^4 give cumulative numerators 1,5,11,15,16.
    for (alpha, k) in [
        (1. / 16., 0.),
        (5. / 16., 1.),
        ((5f64 / 16.).next_up(), 2.),
        (11. / 16., 2.),
        (15. / 16., 3.),
    ] {
        near(binomial(4., 0.5, alpha, meter), k, 0.);
    }
    near(binomial(4.9, 0.5, 0.5, meter), 2., 0.);
    near(binomial(0., 0.5, 0.5, meter), 0., 0.);
}
#[test]
fn numerical_domains_and_operational_channels() {
    assert_eq!(beta(0., 1., 1., 0., 1., meter), Err(num()));
    assert_eq!(binomial(4., 0., 0.5, meter), Err(num()));
    assert_eq!(chi_square(0.5, 1e10 + 1., Tail::Lower, meter), Err(num()));
    assert_eq!(fisher_f(0.5, 2., 1e10, Tail::Upper, meter), Err(num()));
    assert_eq!(student_t(1., 1., false, meter), Err(num()));
    assert_eq!(student_t(1., 1., true, meter), Ok(0.));
    assert_eq!(
        confidence(0.5, 1., 1., ConfidenceKind::Student, meter),
        Err(Failure::Spreadsheet(CellError::Div0))
    );
    assert_eq!(gamma(0., 1., 2., Tail::Lower, meter), Ok(0.));
    assert_eq!(gamma(1., 1., 2., Tail::Lower, meter), Err(num()));
    assert_eq!(
        beta(0.5, 1e13, 1., 0., 1., meter),
        Err(Failure::ComputationalLimit)
    );
    for allowed in [0, 3, 30] {
        let mut used = 0;
        let result = beta(0.3, 2.3, 4.7, 0., 1., |w| {
            used += w;
            if used > allowed {
                Err("budget")
            } else {
                Ok(())
            }
        });
        assert_eq!(result, Err(Failure::Operational("budget")));
    }
}
