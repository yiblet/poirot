#[test]
fn retained_logs_recover_subnormal_factors_before_scaling() {
    let b = beta(1e-161, 0.5, 1., 0., 1e308, meter).unwrap();
    assert!((b / 1e-14 - 1.).abs() < 3e-13);
    let g = gamma(1e-161, 0.5, 1e308, Tail::Lower, meter).unwrap();
    assert!((g / (std::f64::consts::PI * 0.25 * 1e-14) - 1.).abs() < 3e-13);
    let tiny = f64::from_bits(1);
    let c = confidence(1e-300, tiny, 2., ConfidenceKind::Student, meter).unwrap();
    let expected = (2. / std::f64::consts::PI) * (tiny / 1e-300) / 2f64.sqrt();
    assert!((c / expected - 1.).abs() < 3e-13, "{c:e} != {expected:e}");
    let c = confidence(tiny, 1e-100, 2., ConfidenceKind::Student, meter).unwrap();
    let expected =
        ((2. / std::f64::consts::PI).ln() - tiny.ln() - 100. * 10f64.ln() - 0.5 * 2f64.ln()).exp();
    assert!((c / expected - 1.).abs() < 5e-13, "{c:e} != {expected:e}");
    assert!(matches!(
        beta_point_bounded(0.3, 2., 3., 0, meter),
        Err(Failure::NonConvergence)
    ));
    assert_eq!(gamma(f64::NAN, 1., 1., Tail::Lower, meter), Err(num()));
}
#[test]
fn independent_large_shape_integral_controls_certify_containing_brackets() {
    for (a, x, p, tail) in [
        (5e9, 5e9_f64, 0.4999981193680548, Tail::Upper),
        (5e9, 5000212132.034356, 0.001350065171965621, Tail::Upper),
        (5e9, 4997878679.656441, 4.3201286918085546e-198, Tail::Lower),
        (5e9, 5002121320.343559, 5.572494067370442e-198, Tail::Upper),
    ] {
        let actual = gamma(p, a, 1., tail, meter).unwrap();
        assert!(
            actual.to_bits().abs_diff(x.to_bits()) <= 4,
            "{a} {p:e}: {actual} != {x}"
        );
    }
    for (a, b, p, x) in [
        (2e9, 1e9, 0.4999982832240533, 2_f64 / 3.),
        (1e10, 1e10, 0.61135129460711, 0.500001),
    ] {
        let actual = beta(p, a, b, 0., 1., meter).unwrap();
        assert!(
            actual.to_bits().abs_diff(x.to_bits()) <= 4,
            "{actual} != {x}"
        );
    }
}

