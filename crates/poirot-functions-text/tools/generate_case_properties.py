"""Generate Unicode15 casing context ranges; retain the adjacent Unicode notice.
Input: https://www.unicode.org/Public/15.0.0/ucd/DerivedCoreProperties.txt
Usage: python3 generate_case_properties.py DerivedCoreProperties.txt output.rs
"""
import hashlib
from pathlib import Path
import sys

source = Path(sys.argv[1]).read_bytes()
if hashlib.sha256(source).hexdigest() != 'd367290bc0867e6b484c68370530bdd1a08b6b32404601b8c7accaf83e05628d':
    raise SystemExit('Unicode15 input digest mismatch')
properties = {'Cased': [], 'Case_Ignorable': []}
for line in source.decode().splitlines():
    fields = line.split('#')[0].strip().split(';')
    if len(fields) != 2 or fields[1].strip() not in properties:
        continue
    ends = fields[0].strip().split('..')
    properties[fields[1].strip()].append((int(ends[0], 16), int(ends[-1], 16)))
output = ['//! Unicode15 casing context properties; generated by generate_case_properties.py.',
          '//! Copyright © 2022 Unicode, Inc. See UNICODE-LICENSE.txt.',
          '//! Source: https://www.unicode.org/Public/15.0.0/ucd/DerivedCoreProperties.txt']
for name, ranges in properties.items():
    output.append(f'pub(super) const {name.upper()}: &[(u32, u32)] = &[')
    for start, end in ranges:
        output.append(f'    (0x{start:x}, 0x{end:x}),')
    output.append('];')
Path(sys.argv[2]).write_text('\n'.join(output) + '\n')
